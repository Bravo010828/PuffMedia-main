def draw_cards(n=1):
    """随机抽n张牌，返回牌名+正逆位"""
    drawn = random.sample(cards, n)
    results = []
    for card in drawn:
        orientation = random.choice(["正位", "逆位"])
        results.append(f"{card}（{orientation}）")
    return results

def main():
    print("🔮 塔罗牌抽取程序 🔮")
    try:
        n = int(input("请输入要抽几张牌: "))
        print("请集中意念")
        time.sleep(10)
    except ValueError:
        print("输入无效，默认抽1张。")
        n = 1
    drawn_cards = draw_cards(n)
    print("\n抽到的牌：")
    for i, card in enumerate(drawn_cards, 1):
        print(f"{i}. {card}")

if __name__ == "__main__":
    main()
